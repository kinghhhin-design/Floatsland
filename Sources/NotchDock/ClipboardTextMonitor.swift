import AppKit

/// Reads newly copied text. Never writes to the clipboard or imports its startup contents.
final class ClipboardTextMonitor {
    private let store: ShelfStore
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var observedChange: Int
    private var wasEnabled: Bool

    init(store: ShelfStore, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.pasteboard = pasteboard
        observedChange = pasteboard.changeCount
        wasEnabled = AppSettings.shared.captureClipboardText
    }

    func start() {
        guard timer == nil else { return }
        observedChange = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() { timer?.invalidate(); timer = nil }
    deinit { timer?.invalidate() }

    private func poll() {
        let change = pasteboard.changeCount
        let enabled = AppSettings.shared.captureClipboardText
        guard enabled && wasEnabled else {
            observedChange = change
            wasEnabled = enabled
            return
        }
        guard change != observedChange else { return }
        let types = pasteboard.types ?? []
        guard Self.accepts(types: types) else { observedChange = change; return }
        guard let text = pasteboard.string(forType: .string), pasteboard.changeCount == change else { return }
        observedChange = change
        // ShelfStore preserves the original string and deduplicates exact matches.
        if let text = Self.nonemptyText(text) { store.add(text: text) }
    }

    static func accepts(types: [NSPasteboard.PasteboardType]) -> Bool {
        let excluded: Set<NSPasteboard.PasteboardType> = [
            .fileURL, .png, .tiff,
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        ]
        return types.contains(.string) && excluded.isDisjoint(with: types)
    }

    static func nonemptyText(_ text: String) -> String? {
        text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : text
    }
}
